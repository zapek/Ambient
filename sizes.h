/*
 * Common size definition used
 * by panels and icons.
 */
#define SIZE_MICRO  16
#define SIZE_SMALL  24
#define SIZE_MEDIUM 32
#define SIZE_LARGE  48
#define SIZE_HUGE   64

/*
 * Icon sizes as saved in the
 * prefs and in the cycle object.
 */
enum {
	ICON_SIZE_MICRO,
	ICON_SIZE_SMALL,
	ICON_SIZE_MEDIUM,
	ICON_SIZE_LARGE,
	ICON_SIZE_HUGE,
};

#endif /* AMBIENT_SIZES_H */
